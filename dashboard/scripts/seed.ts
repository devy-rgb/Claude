/**
 * Seeds `daily_ad_metrics` with realistic mock data.
 *
 *   npm run seed              -> upserts directly into Supabase (needs SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY)
 *   npm run seed:sql          -> writes supabase/seed.sql to paste into the Supabase SQL editor
 *
 * Options: --end YYYY-MM-DD (last day of data, default yesterday)  --days N (default 120)
 */
import { config } from "dotenv";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createClient } from "@supabase/supabase-js";
import { addDays, isIsoDate, toIso } from "../lib/dates";
import { generateMockMetrics, MOCK_DAYS } from "../lib/mock-data";

config({ path: [".env.local", ".env"] });

const args = process.argv.slice(2);
const arg = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};

const end = arg("end") ?? addDays(toIso(new Date()), -1);
if (!isIsoDate(end)) throw new Error(`--end must be YYYY-MM-DD, got ${end}`);
const days = Number(arg("days") ?? MOCK_DAYS);
const rows = generateMockMetrics(end, days);
console.log(`Generated ${rows.length} rows from ${rows[0]?.date} to ${end}.`);

async function main() {
  if (args.includes("--sql")) {
    const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
    const values = rows.map(
      (r) =>
        `(${q(r.date)},${q(r.ad_id)},${q(r.campaign_name)},${q(r.ad_name)},${r.meta_spend},${r.meta_impressions},${r.meta_clicks},${r.rt_conversions},${r.rt_revenue})`,
    );
    const chunks: string[] = [];
    for (let i = 0; i < values.length; i += 500) {
      chunks.push(
        `insert into public.daily_ad_metrics (date, ad_id, campaign_name, ad_name, meta_spend, meta_impressions, meta_clicks, rt_conversions, rt_revenue) values\n${values
          .slice(i, i + 500)
          .join(",\n")}\non conflict (date, ad_id) do update set campaign_name = excluded.campaign_name, ad_name = excluded.ad_name, meta_spend = excluded.meta_spend, meta_impressions = excluded.meta_impressions, meta_clicks = excluded.meta_clicks, rt_conversions = excluded.rt_conversions, rt_revenue = excluded.rt_revenue;`,
      );
    }
    const out = join(process.cwd(), "supabase", "seed.sql");
    writeFileSync(out, `-- Mock data: ${rows.length} rows, ${rows[0]?.date} to ${end}. Generated by scripts/seed.ts\n\n${chunks.join("\n\n")}\n`);
    console.log(`Wrote ${out}`);
    return;
  }

  const url = process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    throw new Error("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env.local (or run `npm run seed:sql`).");
  }
  const db = createClient(url, key, { auth: { persistSession: false } });
  for (let i = 0; i < rows.length; i += 500) {
    const { error } = await db.from("daily_ad_metrics").upsert(rows.slice(i, i + 500), { onConflict: "date,ad_id" });
    if (error) throw error;
    console.log(`Upserted ${Math.min(i + 500, rows.length)}/${rows.length}`);
  }
  console.log("Done.");
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
